import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { captureResult, snapshot } from './check.mjs';

const [target, output, planPath, ...extra] = process.argv.slice(2);
if (!target || !output || !planPath || extra.length) throw new Error('Usage: prepare.mjs <target-checkout> <new-record-directory> <capture-plan.json>');
const plan = JSON.parse(readFileSync(planPath, 'utf8'));
if (!Array.isArray(plan.paths) || plan.paths.length === 0 || new Set(plan.paths).size !== plan.paths.length) throw new Error('Capture plan requires unique paths');
const modelPath = resolve(target,'.pfdsl/roadmap.pfdsl');
const modelSource = readFileSync(modelPath,'utf8');
const ready = JSON.parse(execFileSync(process.execPath,[resolve(target,'packages/cli/dist/cli.js'),'status','ready',modelPath,'--json'],{encoding:'utf8'}));
if (!ready.ok || !Array.isArray(ready.ready)) throw new Error('CLI ready query failed');
const selected = ready.ready.find(process => process.id === plan.processId);
if (!selected) throw new Error('Selected process is not ready; no trial was prepared');
if (!plan.outputPaths || selected.outputs.some(id => !Array.isArray(plan.outputPaths[id]) || plan.outputPaths[id].length === 0 || plan.outputPaths[id].some(path => !plan.paths.includes(path)))) throw new Error('Capture plan must bind every selected output to captured paths');
const scope = { modelPath: '.pfdsl/roadmap.pfdsl', artifacts: Object.fromEntries(plan.paths.map(path => [path, null])) };
const { artifacts } = captureResult(scope, target);
const context = snapshot(modelSource,ready.ready,artifacts);
context.sourceCommit = execFileSync('git',['-C',target,'rev-parse','HEAD'],{encoding:'utf8'}).trim();
context.modelPath = '.pfdsl/roadmap.pfdsl';
context.processId = plan.processId;
context.requiresResult = true;
context.outputPaths = plan.outputPaths;
context.modelBlob = execFileSync('git',['-C',target,'hash-object',modelPath],{encoding:'utf8'}).trim();
context.note = 'Working files captured before driver generation; content digests identify uncommitted artifact versions.';
mkdirSync(output);
writeFileSync(resolve(output,'snapshot.json'),`${JSON.stringify(context,null,2)}\n`, { flag: 'wx' });
writeFileSync(resolve(output,'ready.json'),`${JSON.stringify(ready,null,2)}\n`, { flag: 'wx' });
