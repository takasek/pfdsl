// Denies a direct Edit/Write of the repository-root instruction documents —
// CLAUDE.md and AGENTS.md — now that both are rendered from
// scripts/root-instructions-template/INSTRUCTIONS.md (#1160). A hand-edit
// there survives only until the next `make gen-plugin`, which silently
// overwrites it (#666, #579's shape). Deny rather than ask: the fix (edit the
// template instead) is a single retry with the message's own path, so there
// is no ask-worthy judgment call to defer to a human.
//
// Scoped to the target's worktree root in the session's repository — not any
// path merely named CLAUDE.md/AGENTS.md — so a hand-authored file that happens
// to share the name (e.g. scripts/skill-template/CLAUDE.md, a dev-only guard
// for a different directory) is never blocked.

import { GENERATED_DISTRIBUTION_SOURCES } from "./distribution-sources.mjs";
import {
	fileTargetScope,
	isFileEditTool,
	resolveFileTargetContext,
} from "./file-target-context.mjs";

// Derived from the one mapping that already records "this file is rendered
// from that source", so a third template-rendered root file is guarded by
// adding it there alone. The repository-root test is the key having no
// directory separator — every other entry in that mapping is a bundled path
// under plugin/ or generated/.
export const GENERATED_ROOT_INSTRUCTION_FILES = Object.freeze(
	Object.fromEntries(
		Object.entries(GENERATED_DISTRIBUTION_SOURCES).filter(
			([name]) => !name.includes("/"),
		),
	),
);

/**
 * Could this resolved filesystem path be a guarded root file by name?
 * Resolve symlinks before this check: an alias can have a different basename.
 * @param {unknown} filePath
 * @returns {boolean}
 */
export function mayTargetGeneratedRootInstructions(filePath) {
	if (typeof filePath !== "string") return false;
	return Object.keys(GENERATED_ROOT_INSTRUCTION_FILES).some((name) =>
		filePath.endsWith(`/${name}`),
	);
}

/**
 * Decide whether a file edit targets generated instructions in this repository.
 * @param {object} payload PreToolUse hook payload
 * @param {object} [context] resolved target context, injectable for tests
 * @returns {{decision: "allow"} | {decision: "deny", reason: string}}
 */
export function evaluateGeneratedRootInstructionsGuard(payload, context) {
	if (!isFileEditTool(payload)) return { decision: "allow" };
	context ??= resolveFileTargetContext(payload);
	if (context.error) return { decision: "deny", reason: context.error };
	for (const target of context.targets) {
		if (!mayTargetGeneratedRootInstructions(target.path)) continue;
		const scope = fileTargetScope(target, context.sessionRoots);
		if (scope === "outside") continue;
		if (scope === "unknown") {
			return {
				decision: "deny",
				reason: `Cannot resolve the repository for '${target.path}'. Check the target checkout before editing generated instructions.`,
			};
		}
		const name = Object.keys(GENERATED_ROOT_INSTRUCTION_FILES).find(
			(name) => target.path === `${target.roots.worktreeRoot}/${name}`,
		);
		if (!name) continue;
		const source = `${target.roots.worktreeRoot}/${GENERATED_ROOT_INSTRUCTION_FILES[name]}`;
		return {
			decision: "deny",
			reason: `${target.path} is generated by scripts/lib/gen-plugin.mjs from ${source}. Edit ${source} instead, then run 'make gen-plugin' in '${target.roots.worktreeRoot}' to regenerate ${name}.`,
		};
	}
	return { decision: "allow" };
}
