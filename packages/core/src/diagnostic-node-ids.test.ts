describe("diagnostic node IDs", () => {
	it("sort, reindex and delete retain the original diagnostics", () => {
		const source = "p -> a\nq -> a\nr -> a\n";
		const diagnostics = analyze(source).diagnostics;
		expect(diagnostics.find((d) => d.code === "V001")?.nodeIds).toEqual([
			"a",
			"p",
			"q",
			"r",
		]);
		for (const result of [
			sort(source, { by: ["id"] }),
			reindex(source),
			deleteNodes(source, ["a"]),
		]) {
			expect(result.diagnostics).toEqual(diagnostics);
		}
	});

	it("rename forwards unreadable diagnostics without projecting their fields", () => {
		const source = "a >>";
		const analysis = analyze(source);
		// Rename only returns FM/L/P errors; exercise forwarding with an optional field.
		analysis.diagnostics[0]!.nodeIds = ["a"];
		const result = rename(source, "a", "b", { analysis });
		expect(result).toEqual({
			ok: false,
			reason: "unreadable",
			diagnostics: analysis.diagnostics,
		});
	});

	it("V010 deduplicates a self loop even when node kinds conflict", () => {
		const model = analyze("a >> a");
		expect(model.diagnostics.filter((d) => d.code === "V010")).toEqual([
			{
				code: "V010",
				severity: "error",
				nodeIds: ["a"],
				message: "Primary graph contains a cycle involving 'a' → 'a'",
				range: {
					start: { line: 1, column: 1, offset: 0 },
					end: { line: 1, column: 7, offset: 6 },
				},
			},
		]);
	});
	it.each(
		cases,
	)("%s targets its nodes without changing the diagnostic", (code, source, raw, nodeIds, message, severity) => {
		const fm = raw as unknown as Frontmatter;
		const { document } = parseTokens(lex(source).tokens);
		const normalized = normalize(document, fm);
		const ctx = buildRuleContext(normalized.edges, normalized.nodeKinds, fm, {
			strict: code === "V011",
		});
		const diagnostics = [
			...normalized.diagnostics,
			...RULES.flatMap((rule) => rule(ctx)),
		].filter((d) => d.code === code);
		expect(diagnostics).toEqual([
			{
				code,
				severity: severity ?? "error",
				message,
				range: zeroRange(),
				nodeIds: [...nodeIds],
			},
		]);
	});

	it("V010 reports only the stack cycle for each back edge, in traversal order", () => {
		const source =
			"entry >> start -> a\na >> p -> b\nb >> q -> a\nb >> r -> a\nx >> s -> y\ny >> t -> x";
		const { document } = parseTokens(lex(source).tokens);
		const { edges, nodeKinds } = normalize(document, null);
		const ctx = buildRuleContext(edges, nodeKinds, null, { document });
		const diagnostics = RULES.flatMap((rule) => rule(ctx)).filter(
			(d) => d.code === "V010",
		);
		expect(diagnostics).toEqual([
			{
				code: "V010",
				severity: "error",
				message: "Primary graph contains a cycle involving 'q' → 'a'",
				nodeIds: ["a", "p", "b", "q"],
				range: {
					start: { line: 3, column: 6, offset: 37 },
					end: { line: 3, column: 12, offset: 43 },
				},
			},
			{
				code: "V010",
				severity: "error",
				message: "Primary graph contains a cycle involving 'r' → 'a'",
				nodeIds: ["a", "p", "b", "r"],
				range: {
					start: { line: 4, column: 6, offset: 49 },
					end: { line: 4, column: 12, offset: 55 },
				},
			},
			{
				code: "V010",
				severity: "error",
				message: "Primary graph contains a cycle involving 't' → 'x'",
				nodeIds: ["x", "s", "y", "t"],
				range: {
					start: { line: 6, column: 6, offset: 73 },
					end: { line: 6, column: 12, offset: 79 },
				},
			},
		]);
	});

	it("document settings and both V009 sites omit nodeIds", () => {
		const fm = {
			baseRef: { source: " ", revision: "r" },
			type: "bad",
			statusStyles: { bad: { bad: "x" } },
			tag: { tag: { style: { bad: "x" } } },
		} as unknown as Frontmatter;
		const diagnostics = RULES.flatMap((rule) =>
			rule(buildRuleContext([], new Map(), fm)),
		);
		expect(diagnostics.map((d) => d.code)).toEqual([
			"V008",
			"V009",
			"V009",
			"V031",
			"V037",
		]);
		for (const diagnostic of diagnostics)
			expect(diagnostic).not.toHaveProperty("nodeIds");
	});
});
